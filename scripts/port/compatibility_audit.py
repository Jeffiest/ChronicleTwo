#!/usr/bin/env python3
"""Bounded source inventory for host compatibility hazards.

This is a lexical inventory, not a C++ parser or reachability proof. See
docs/port/COMPATIBILITY_AUDIT.md for the detector boundaries.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

EXCLUDED = {"build", "generated", "third_party", "vendor"}
SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx"}
MARKER = "<!-- Generated by scripts/port/compatibility_audit.py; do not edit below. -->"

# Bounded lexical families. Keep expressions narrow enough to avoid counting
# ordinary integer casts as pointer narrowing.
ALLOC = re.compile(r"(?P<expr>\([^;\n]*?\*\)\s*[^;\n]*?\b(?:Alloc|stAlloc)\s*\([^;\n]*?\))")
ALLOC_REINTERPRET = re.compile(r"(?P<expr>reinterpret_cast\s*<[^;\n>]*\*\s*>\s*\([^;\n]*?\b(?:Alloc|stAlloc)\s*\([^;\n]*?\))")
CAST = re.compile(r"(?P<expr>(?:\(\s*(?:u?int(?:8|16|32|64)_t|u?long|u?int|uintptr_t|intptr_t)\s*\)\s*[^;\n]*(?:\bthis\b|\b[a-zA-Z_]\w*\s*\*|reinterpret_cast)|(?:reinterpret_cast|static_cast)\s*<\s*(?:u?int(?:8|16|32|64)_t|u?long|u?int|uintptr_t|intptr_t)\s*>\s*\([^;\n]*\b(?:this|[a-zA-Z_]\w*)\s*\*))")
OFFSET = re.compile(r"(?P<expr>(?:\(\s*(?:const\s+)?(?:u?int8_t|u8|s8|u_char|char|unsigned char)\s*\*\s*\)\s*(?:this|[A-Za-z_]\w*)|reinterpret_cast\s*<\s*(?:const\s+)?(?:u?int8_t|u8|s8|u_char|char|unsigned char)\s*\*>\s*\(\s*(?:this|[A-Za-z_]\w*)\s*\))[^;\n]*\+\s*(?:0x[0-9a-fA-F]+|\d+|sizeof\s*\([^)]*\)))")
BYTE_PTR_DECL = re.compile(r"\b(?:const\s+)?(?:u?int8_t|u8|s8|u_char|char|unsigned char)\s*\*+\s*(?P<name>[A-Za-z_]\w*)\s*=\s*(?:\([^)]*\*\)|reinterpret_cast\s*<[^>]+>)")
ALIAS_OFFSET = re.compile(r"(?P<expr>\b(?P<name>[A-Za-z_]\w*)\s*\+\s*(?:[A-Za-z_]\w*|0x[0-9a-fA-F]+|\d+))")
POINTER_ARRAY_OFFSET = re.compile(r"(?P<expr>\(\s*[\w:]+\s*\*\s*\*\s*\)\s*\(\s*\(\s*(?:u?int8_t|u8|s8|u_char|char|unsigned char)\s*\*\s*\)\s*[A-Za-z_]\w*\s*\+[^;\n]*?\))")
HARDWARE = {
    "gs_register": re.compile(r"\b(?:GS_[A-Z0-9_]+|GS_REG|GS_ADDR|GS_DISPFB|GS_DISPLAY|GS_XYZ|GS_RGBA|gsSet[A-Z]\w*)\b"),
    "dma_gif_vif": re.compile(r"\b(?:DMA_[A-Z0-9_]+|DmaChannel|DmaSync|dmaKit|GIF_[A-Z0-9_]+|VIF_[A-Z0-9_]+|sceDma|sceGif|sceVif)\b"),
    "scratchpad": re.compile(r"\b(?:ScratchPad|scratchpad|SPR_BASE|SPR_FROM|SPR_TO|0x70000000)\b", re.I),
    "inline_asm_or_intrinsic": re.compile(r"\b(?:asm|__asm__|__builtin_\w+|__mips__|__mips(?:16|64)__)\b"),
    "ps2_sdk_or_thread": re.compile(r"\b(?:sce[A-Z]\w*|CreateThread|StartThread|TerminateThread|SleepThread|iSignalSema|SignalSema|WaitSema)\b"),
}
FUNC = re.compile(r"(?:^|[;{}])\s*(?:[\w:*&<>~]+\s+)+(?P<name>(?:[\w~]+::)*[\w~]+)\s*\([^;{}]*\)\s*(?:const\s*)?(?:\{|$)")


def source_files(root: Path):
    for path in sorted(root.rglob("*")):
        if path.suffix.lower() not in SOURCE_SUFFIXES or any(part in EXCLUDED for part in path.parts):
            continue
        yield path


def function_name(lines: list[str], index: int) -> str:
    # Search a short preceding window. This deliberately does not attempt to
    # parse templates, macros, lambdas, or declarations split across distant lines.
    for line in reversed(lines[max(0, index - 200):index + 1]):
        m = FUNC.search(line.strip())
        if m:
            return m.group("name")
    return "<file-scope>"


def site_id(category: str, file: str, symbol: str, expression: str) -> str:
    key = "\0".join((category, file.replace("\\", "/"), symbol, re.sub(r"\s+", " ", expression).strip()))
    return hashlib.sha256(key.encode("utf-8")).hexdigest()[:16]


def scan(source_root: Path, host_root: Path) -> list[dict]:
    host_defs: dict[str, set[str]] = {}
    if host_root.exists():
        for p in source_files(host_root):
            txt = p.read_text(encoding="latin-1")
            for match in re.finditer(r"\bPORT_OVERRIDE\s+(?:[\w:*&<>~]+\s+)+(?:[\w~]+::)?(?P<name>[\w~]+)\s*\(", txt):
                host_defs.setdefault(match.group("name"), set()).add(p.relative_to(host_root).as_posix())

    rows: list[dict] = []
    trees = [(source_root, "retail")]
    if host_root.exists():
        trees.append((host_root, "host-source"))
    for tree, role in trees:
        for path in source_files(tree):
            rel = path.relative_to(tree).as_posix()
            file_label = f"{role}/{rel}"
            lines = path.read_text(encoding="latin-1").splitlines()
            byte_pointer_names = {m.group("name") for line in lines for m in BYTE_PTR_DECL.finditer(line)}
            for number, line in enumerate(lines, 1):
                matches: list[tuple[str, str]] = []
                for m in ALLOC.finditer(line):
                    matches.append(("raw-allocation", m.group("expr")))
                for m in ALLOC_REINTERPRET.finditer(line):
                    matches.append(("raw-allocation", m.group("expr")))
                for m in CAST.finditer(line):
                    matches.append(("pointer-narrowing", m.group("expr")))
                for m in OFFSET.finditer(line):
                    matches.append(("raw-member-offset", m.group("expr")))
                for m in POINTER_ARRAY_OFFSET.finditer(line):
                    matches.append(("byte-stride-pointer-array", m.group("expr")))
                for m in ALIAS_OFFSET.finditer(line):
                    if m.group("name") in byte_pointer_names:
                        matches.append(("raw-member-offset", m.group("expr")))
                for category, pattern in HARDWARE.items():
                    m = pattern.search(line)
                    if m:
                        matches.append(("hardware:" + category, m.group(0)))
                if not matches:
                    continue
                symbol = function_name(lines, number - 1)
                for category, expr in matches:
                    norm = re.sub(r"\s+", " ", expr).strip()
                    host = sorted(host_defs.get(symbol.split("::")[-1], set()))
                    rows.append({
                        "id": site_id(category, file_label, f"{symbol}@{number}", norm),
                        "category": category,
                        "site": f"{file_label}:{number}",
                        "file": file_label,
                        "line": number,
                        "symbol": symbol,
                        "expression": norm,
                        "host_override": ", ".join(host) if role == "retail" and host else (file_label if role == "host-source" else "none detected"),
                    })
    # A site can match more than one lexical detector; preserve each category.
    return sorted(rows, key=lambda r: (r["file"], r["line"], r["category"], r["id"]))


def render_inventory(rows: list[dict]) -> str:
    out = ["# Port compatibility source inventory", "", "Generated lexical inventory. Human status and rationale live in `compatibility_decisions.tsv`.", "", MARKER, ""]
    out += ["| ID | Category | Retail source site | Function | Expression/token | Host override candidate |", "|---|---|---|---|---|---|"]
    for r in rows:
        cells = [r["id"], r["category"], r["site"], r["symbol"], r["expression"], r["host_override"]]
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |")
    out.append("")
    return "\n".join(out)


def read_ledger(path: Path) -> dict[str, dict[str, str]]:
    if not path.exists():
        return {}
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines:
        return {}
    headers = lines[0].split("\t")
    result = {}
    for line in lines[1:]:
        if not line.strip() or line.startswith("#"):
            continue
        values = line.split("\t")
        row = dict(zip(headers, values))
        if row.get("id"):
            result[row["id"]] = row
    return result


def render_ledger(rows: list[dict], old: dict[str, dict[str, str]]) -> str:
    cols = ["id", "status", "reviewed_by", "rationale"]
    out = ["\t".join(cols)]
    for r in rows:
        prev = old.get(r["id"], {})
        out.append("\t".join([r["id"], prev.get("status", "open"), prev.get("reviewed_by", ""), prev.get("rationale", "")]))
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source-root", type=Path, default=Path("ps2"), help="retail source tree to inventory")
    parser.add_argument("--host-root", type=Path, default=Path("port"), help="effective host implementation tree")
    parser.add_argument("--inventory", type=Path, default=Path("docs/port/COMPATIBILITY_INVENTORY.md"))
    parser.add_argument("--decisions", type=Path, default=Path("docs/port/compatibility_decisions.tsv"))
    parser.add_argument("--write", action="store_true", help="regenerate inventory and add new rows as open")
    parser.add_argument("--check", action="store_true", help="fail on stale inventory or missing/stale decision rows")
    args = parser.parse_args()
    rows = scan(args.source_root, args.host_root)
    generated = render_inventory(rows)
    old = read_ledger(args.decisions)
    expected_ledger = render_ledger(rows, old)
    if args.write:
        args.inventory.parent.mkdir(parents=True, exist_ok=True)
        args.decisions.parent.mkdir(parents=True, exist_ok=True)
        args.inventory.write_text(generated, encoding="utf-8", newline="\n")
        args.decisions.write_text(expected_ledger, encoding="utf-8", newline="\n")
    if args.check:
        failures = []
        if not args.inventory.exists() or args.inventory.read_text(encoding="utf-8") != generated:
            failures.append(f"stale inventory: run {Path(__file__).as_posix()} --write and review the diff")
        ids = {r["id"] for r in rows}
        missing, stale = ids - set(old), set(old) - ids
        if missing:
            failures.append("unreviewed source sites missing from decision ledger: " + ", ".join(sorted(missing)))
        if stale:
            failures.append("decision rows without source sites: " + ", ".join(sorted(stale)))
        if not args.decisions.exists():
            failures.append(f"missing decision ledger: {args.decisions}")
        if failures:
            print("\n".join(f"compatibility_audit: {f}" for f in failures), file=sys.stderr)
            return 1
    print(f"compatibility_audit: {len(rows)} source findings; output {'checked' if args.check else 'scanned'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
